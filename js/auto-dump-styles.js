function rect(x,y,w,h){return{x,y,w,h}}
function gridRects(n,w=SW,h=SH,margin=36,gap=18){
  const Wd=w-margin*2,Hd=h-margin*2;
  if(n<=1)return[rect(margin,margin,Wd,Hd)];
  if(n===2){const cw=(Wd-gap)/2;return[rect(margin,margin,cw,Hd),rect(margin+cw+gap,margin,cw,Hd)]}
  if(n===3){const hero=Math.round(Wd*.58),side=Wd-hero-gap,rh=(Hd-gap)/2;return[rect(margin,margin,hero,Hd),rect(margin+hero+gap,margin,side,rh),rect(margin+hero+gap,margin+rh+gap,side,rh)]}
  if(n===4){const cw=(Wd-gap)/2,rh=(Hd-gap)/2;return[rect(margin,margin,cw,rh),rect(margin+cw+gap,margin,cw,rh),rect(margin,margin+rh+gap,cw,rh),rect(margin+cw+gap,margin+rh+gap,cw,rh)]}
  if(n===5){const top=Math.round(Hd*.47),bottom=Hd-top-gap,cw=(Wd-gap)/2,rh=(bottom-gap)/2,y=margin+top+gap;return[rect(margin,margin,Wd,top),rect(margin,y,cw,rh),rect(margin+cw+gap,y,cw,rh),rect(margin,y+rh+gap,cw,rh),rect(margin+cw+gap,y+rh+gap,cw,rh)]}
  const cols=n<=8?2:n<=12?3:n<=20?4:n<=35?5:6,rows=Math.ceil(n/cols);
  const cw=(Wd-gap*(cols-1))/cols,rh=(Hd-gap*(rows-1))/rows,a=[];
  for(let i=0;i<n;i++){const row=Math.floor(i/cols),col=i%cols;a.push(rect(margin+col*(cw+gap),margin+row*(rh+gap),cw,rh))}
  return a;
}
function editorialRects(n){
  if(n<=1)return gridRects(n);
  const m=46,g=18,Wd=SW-m*2,Hd=SH-m*2,heroW=Math.round(Wd*.58),sideW=Wd-heroW-g,a=[rect(m,m,heroW,Hd)];
  const rest=n-1,rows=Math.ceil(rest/2),rh=(Hd-g*(rows-1))/rows;
  for(let i=0;i<rest;i++){const row=Math.floor(i/2),col=i%2,w=rest>3?(sideW-g)/2:sideW,x=m+heroW+g+col*(w+g);a.push(rect(x,m+row*(rh+g),w,rh))}
  return a.slice(0,n);
}
function magazineRects(n){
  const m=48,g=20,Wd=SW-m*2,Hd=SH-m*2;
  if(n<=1)return[rect(m,m,Wd,Hd)];
  const heroH=Math.round(Hd*.58),a=[rect(m,m,Wd,heroH)],rest=n-1,cols=Math.min(rest,3),rows=Math.ceil(rest/cols),cw=(Wd-g*(cols-1))/cols,rh=(Hd-heroH-g-g*(rows-1))/rows;
  for(let i=0;i<rest;i++){const row=Math.floor(i/cols),col=i%cols;a.push(rect(m+col*(cw+g),m+heroH+g+row*(rh+g),cw,rh))}
  return a;
}
function postcardRects(n){
  const m=70,g=26,Wd=SW-m*2,Hd=SH-m*2,cols=n<=3?1:2,rows=Math.ceil(n/cols),cw=(Wd-g*(cols-1))/cols,rh=(Hd-g*(rows-1))/rows,a=[];
  for(let i=0;i<n;i++){const row=Math.floor(i/cols),col=i%cols;a.push(rect(m+col*(cw+g)+(row%2?10:-8),m+row*(rh+g),cw-12,rh-10))}
  return a;
}
function styleRects(style,n){
  if(style==='editorial')return editorialRects(n);
  if(style==='magazine')return magazineRects(n);
  if(style==='postcard')return postcardRects(n);
  if(style==='film')return gridRects(n,SW,SH,54,14);
  if(style==='contact')return gridRects(n,SW,SH,42,10);
  if(style==='soft')return gridRects(n,SW,SH,46,24);
  if(style==='paper'||style==='polaroid')return gridRects(n,SW,SH,62,28);
  return gridRects(n);
}
function groups(total,target){
  const slides=clamp(Math.ceil(total/target),1,MAX_SLIDES),base=Math.floor(total/slides),rem=total%slides;
  return Array.from({length:slides},(_,i)=>base+(i<rem?1:0));
}
