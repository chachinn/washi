function slidePalette(style,slide){const a=PALETTES[style]||PALETTES.clean;return a[slide%a.length]}

function prepareMode(p,mode,count){
  if(mode==='collage'){
    p.width=SW;p.height=SH;p.format='dump';delete p.carousel;
  }else{
    const target=mode==='video'?6:mode==='carousel'?5:4,g=groups(count,target),n=g.length;
    p.width=SW*n;p.height=SH;p.format='portrait';
    p.carousel={enabled:true,slideCount:n,slideWidth:SW,slideHeight:SH,durations:Array(n).fill(mode==='video'?2.4:3),activeSlide:0,view:'slide'};
    return g;
  }
  return[count];
}
function layoutWithStyle(p,mode,styleId){
  const media=photos(p);
  if(!media.length)return;
  const extras=(p.objects||[]).filter(o=>!media.includes(o)&&!o.autoDumpDecor&&!o.autoBackground);
  const gs=prepareMode(p,mode,media.length),backs=[],fronts=[];
  let offset=0;
  gs.forEach((count,slide)=>{
    const effective=mode==='pages'?STYLE_IDS[(STYLE_IDS.indexOf(styleId)+slide)%STYLE_IDS.length]:styleId;
    backs.push(bgShape(slide,slidePalette(effective,mode==='pages'?slide:0)));
    const rs=styleRects(effective,count),chunk=media.slice(offset,offset+count);
    chunk.forEach((o,i)=>stylePhoto(o,rs[i],effective,slide,i,backs,fronts));
    slideDecor(effective,slide,count,fronts);
    offset+=count;
  });
  p.objects=[...backs,...media,...fronts,...extras];
  p.bg={type:'solid',value:mode==='collage'?slidePalette(styleId,0):'#fff'};
  p.autoDumpLayout=true;p.autoGenerated=true;p.autoOutput=mode;
  p.autoDumpStudio={...(p.autoDumpStudio||{}),mode,style:styleId,seed:p.autoDumpStudio?.seed||0};
  if(mode==='collage')p.name=`Auto Collage · ${media.length} photos`;
  else if(mode==='pages')p.name=`Auto Templates · ${media.length} photos`;
  else if(mode==='carousel')p.name=`Auto Carousel · ${media.length} photos`;
  else p.name=`Auto Video · ${media.length} photos`;
  E.state.selectedId=null;
  E.render();
  E.save();
  requestAnimationFrame(()=>focus(mode));
}
function focus(mode){
  if(mode==='collage'){E.fit();return}
  const p=project(),w=$('#editorWorkspace'),sc=$('#stageScroll');if(!p||!w||!sc)return;
  const z=Math.min((w.clientWidth-42)/SW,(w.clientHeight-185)/SH,1);
  E.setZoom(z);
  sc.style.placeItems='center start';
  requestAnimationFrame(()=>sc.scrollTo({left:0,top:0,behavior:'auto'}));
}
function inferMode(p){
  if(p?.autoDumpStudio?.mode)return p.autoDumpStudio.mode;
  if(p?.autoOutput==='video')return'video';
  if(p?.autoOutput==='carousel')return'carousel';
  if(p?.autoOutput==='pages')return'pages';
  return'collage';
}
function inferStyle(p){return STYLE_IDS.includes(p?.autoDumpStudio?.style)?p.autoDumpStudio.style:'clean'}
function suggestionIds(p){
  const s=p.autoDumpStudio||(p.autoDumpStudio={mode:inferMode(p),style:inferStyle(p),seed:0}),seed=Number(s.seed)||0,len=STYLE_IDS.length;
  return[STYLE_IDS[(seed+1)%len],STYLE_IDS[(seed+4)%len],STYLE_IDS[(seed+7)%len]];
}
