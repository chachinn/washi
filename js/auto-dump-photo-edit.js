(() => {
'use strict';
const W=window.Washi=window.Washi||{},E=W.Editor,F=W.SmartPhotoFill;
if(!E||!F||W.AutoDumpPhotoEdit)return;

const $=(s,r=document)=>r.querySelector(s);
const project=()=>E.getProject?.()||E.state?.project||null;
const selected=()=>E.selected?.()||project()?.objects?.find(o=>o.id===E.state?.selectedId)||null;
const isMedia=o=>!!o&&['image','video'].includes(o.type)&&!!o.mediaId&&!o.isPhotoBackground;
const isAutoDump=p=>!!p&&(p.autoDumpLayout||p.autoGenerated||p.format==='dump'||p.autoDumpStudio);
const editorView=$('#editorView');
const stage=$('#designStage');

function cropActive(){return !!stage?.classList.contains('photo-crop-mode')}

function ensureButton(){
 const dock=$('#washiAutoDumpStudio');
 if(!dock)return null;
 const head=dock.querySelector('.wad-head');
 if(!head)return null;
 let button=head.querySelector('[data-wad-edit-photo]');
 if(!button){
  button=document.createElement('button');
  button.type='button';
  button.className='wad-edit-photo';
  button.dataset.wadEditPhoto='1';
  const shuffle=head.querySelector('[data-wad-shuffle]');
  if(shuffle)head.insertBefore(button,shuffle);
  else head.append(button);
 }
 const o=selected(),show=isAutoDump(project())&&isMedia(o);
 button.hidden=!show;
 if(show){
  button.textContent=cropActive()?'Done':'Edit Photo';
  button.setAttribute('aria-label',cropActive()?'Finish repositioning photo':'Reposition photo inside its frame');
 }
 return button;
}

function beginEdit(){
 const o=selected();
 if(!isAutoDump(project())||!isMedia(o))return false;
 editorView?.classList.add('washi-auto-dump-photo-editing');
 F.enterCrop?.(o);
 if(!cropActive())editorView?.classList.remove('washi-auto-dump-photo-editing');
 ensureButton();
 return cropActive();
}

function finishEdit(save=true){
 if(cropActive())F.exitCrop?.(save);
 editorView?.classList.remove('washi-auto-dump-photo-editing');
 requestAnimationFrame(ensureButton);
}

function sync(){
 if(!cropActive())editorView?.classList.remove('washi-auto-dump-photo-editing');
 ensureButton();
}

document.addEventListener('click',event=>{
 const target=event.target instanceof Element?event.target:null;
 if(!target)return;
 const edit=target.closest('[data-wad-edit-photo]');
 if(edit){
  event.preventDefault();
  event.stopPropagation();
  event.stopImmediatePropagation();
  if(cropActive())finishEdit(true);else beginEdit();
  return;
 }
 if(target.closest('#washiMediaCropHUD [data-crop="done"]')){
  requestAnimationFrame(()=>{
   editorView?.classList.remove('washi-auto-dump-photo-editing');
   ensureButton();
  });
 }
},true);

for(const name of ['washi:selection-changed','washi:project-saved','washi:experience-ready']){
 window.addEventListener(name,()=>requestAnimationFrame(sync));
}
window.addEventListener('resize',()=>requestAnimationFrame(sync),{passive:true});
window.addEventListener('load',()=>requestAnimationFrame(sync),{once:true});
setTimeout(sync,260);

const css=document.createElement('style');
css.textContent=`
#washiAutoDumpStudio .wad-edit-photo{min-height:36px;border:1px solid rgba(200,79,119,.24);border-radius:12px;background:var(--pink-100);color:var(--rose);padding:0 11px;font-size:.72rem;font-weight:900;white-space:nowrap}
#washiAutoDumpStudio .wad-edit-photo[hidden]{display:none!important}
.editor-view.washi-auto-dump-photo-editing #washiAutoDumpStudio{display:none!important}
.editor-view.active #washiMediaCropHUD{z-index:62!important;bottom:calc(var(--washi-nav-height,76px) + 84px)!important;left:12px!important;right:12px!important}
@media(max-width:430px){#washiAutoDumpStudio .wad-edit-photo{padding:0 9px;font-size:.69rem}.editor-view.active #washiMediaCropHUD{bottom:calc(var(--washi-nav-height,76px) + 82px)!important}}
`;
document.head.append(css);

W.AutoDumpPhotoEdit={version:'2026.08.16-r1',beginEdit,finishEdit,sync};
})();
